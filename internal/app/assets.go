package app

import (
	"encoding/json"
	"fmt"
	"html/template"
	"os"
	"path/filepath"
	"sort"
	"strings"
)

type entrypoint struct {
	JS  []string `json:"js"`
	CSS []string `json:"css"`
}

type entrypoints struct {
	Entrypoints map[string]entrypoint `json:"entrypoints"`
	Integrity   map[string]string     `json:"integrity"`
}

// Assets resolves webpack output through manifest.json and entrypoints.json.
type Assets struct {
	manifest  map[string]string
	integrity map[string]string
	entries   map[string]entrypoint
}

func LoadAssets(webDir string) (*Assets, error) {
	buildDir := filepath.Join(webDir, "build")

	manifest := make(map[string]string)
	if err := readJSON(filepath.Join(buildDir, "manifest.json"), &manifest); err != nil {
		return nil, err
	}

	var points entrypoints
	if err := readJSON(filepath.Join(buildDir, "entrypoints.json"), &points); err != nil {
		return nil, err
	}

	return &Assets{
		manifest:  manifest,
		integrity: points.Integrity,
		entries:   points.Entrypoints,
	}, nil
}

func readJSON(path string, target any) error {
	raw, err := os.ReadFile(path)
	if err != nil {
		return err
	}
	if err := json.Unmarshal(raw, target); err != nil {
		return fmt.Errorf("%s: %w", path, err)
	}
	return nil
}

// Asset maps a source path such as "build/css/main.css" to the hashed file.
func (a *Assets) Asset(path string) string {
	if hashed, ok := a.manifest[path]; ok {
		return hashed
	}
	if strings.HasPrefix(path, "/") {
		return path
	}
	return "/" + path
}

// DataScript points at the locale data generated by the translation pipeline.
func (a *Assets) DataScript(locale string) string {
	return "/build/data/" + locale + ".js"
}

func (a *Assets) tags(paths []string) string {
	var builder strings.Builder
	for _, path := range paths {
		if hash, ok := a.integrity[path]; ok {
			builder.WriteString(fmt.Sprintf(` integrity="%s"`, hash))
		}
	}
	return builder.String()
}

func (a *Assets) EncoreCSS(name string) template.HTML {
	entry, ok := a.entries[name]
	if !ok {
		return ""
	}

	var builder strings.Builder
	for _, path := range entry.CSS {
		builder.WriteString(fmt.Sprintf(`<link rel="stylesheet" href="%s"%s>`, path, a.tags([]string{path})))
		builder.WriteString("\n")
	}
	return template.HTML(builder.String())
}

func (a *Assets) EncoreJS(name string) template.HTML {
	entry, ok := a.entries[name]
	if !ok {
		return ""
	}

	var builder strings.Builder
	for _, path := range entry.JS {
		builder.WriteString(fmt.Sprintf(`<script src="%s" defer%s></script>`, path, a.tags([]string{path})))
		builder.WriteString("\n")
	}
	return template.HTML(builder.String())
}

// SortedKeys is used by template helpers that render attribute maps in a
// stable order.
func SortedKeys[V any](values map[string]V) []string {
	keys := make([]string, 0, len(values))
	for key := range values {
		keys = append(keys, key)
	}
	sort.Strings(keys)
	return keys
}
