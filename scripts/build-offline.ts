import { readdir, readFile, writeFile } from "node:fs/promises";
import { createHash } from "node:crypto";
import { join, relative, resolve } from "node:path";
import vm from "node:vm";
import { fileURLToPath } from "node:url";
import { SUPPORTED_ROLE_IDS } from "../src/core/model/role-ids.ts";
import { ALL_TRAVELLER_IDS } from "../src/ui/screens/sheet-scenarios.ts";
import { LOCALE_FILES } from "../src/infrastructure/catalog/locale-files.ts";
import { imageName } from "../src/infrastructure/catalog/role-image.ts";
import type { Role } from "../src/core/model/types.ts";

// Only the catalogs the app can request are worth downloading on every install.
// The artifact keeps the rest, which stay fetchable, but they are neither cached
// nor part of the cache id.
const CATALOG_PREFIX = "assets/data/";
const REACHABLE_CATALOGS = new Set(
  Object.values(LOCALE_FILES).map((name) => `${CATALOG_PREFIX}${name}.js`),
);

// The worker hashes the built artifact, never the source tree. Both arguments
// are required so a caller cannot silently precache the wrong root.
const root = argument("--root");
const out = argument("--out");
if (!root || !out) {
  console.error("Usage: node scripts/build-offline.ts --root <dir> --out <file>");
  process.exit(2);
}

const rootDir = resolve(root);
const outFile = resolve(out);

function argument(name: string): string | null {
  const index = process.argv.indexOf(name);
  return index === -1 ? null : (process.argv[index + 1] ?? null);
}

const files: string[] = [];
async function collect(folder: string) {
  for (const entry of await readdir(join(rootDir, folder), { withFileTypes: true })) {
    const path = folder ? `${folder}/${entry.name}` : entry.name;
    if (entry.isDirectory()) await collect(path);
    else if (resolve(rootDir, path) !== outFile) files.push(path);
  }
}
await collect("");
// The generated CSS can use either stylesheet-relative or deployment-base URLs.
const sheetRoles = new Set<string>([...SUPPORTED_ROLE_IDS, ...ALL_TRAVELLER_IDS]);
const roleArt = new Set<string>();
const fonts = new Set<string>();
for (const path of files) {
  if (REACHABLE_CATALOGS.has(path)) {
    const catalog: { PG?: { roles: Role[] } } = {};
    vm.runInNewContext(await readFile(join(rootDir, path), "utf8"), catalog, { filename: path });
    if (!Array.isArray(catalog.PG?.roles)) throw new Error("Missing role catalog in " + path);
    for (const role of catalog.PG.roles) {
      if (!sheetRoles.has(role.id)) continue;
      const name = imageName(role);
      if (name) roleArt.add("assets/img/roles/" + name);
    }
  } else if (path.endsWith(".css")) {
    const css = await readFile(join(rootDir, path), "utf8");
    for (const match of css.matchAll(/url\(\s*["']?([^)"']+?)["']?\s*\)/gi)) {
      const base = new URL(path, "https://artifact.invalid/");
      const url = new URL(match[1]!, base);
      const index = url.pathname.lastIndexOf("/assets/fonts/");
      if (url.origin === base.origin && index >= 0)
        fonts.add(decodeURIComponent(url.pathname.slice(index + 1)));
    }
  }
}

const paths = [
  "./",
  ...files.filter((path) => {
    if (path.startsWith(CATALOG_PREFIX) && path.endsWith(".js"))
      return REACHABLE_CATALOGS.has(path);
    if (path.startsWith("assets/img/roles/")) return roleArt.has(path);
    if (path.startsWith("assets/fonts/") && /\.(?:woff2?|ttf|otf)$/i.test(path))
      return fonts.has(path);
    return true;
  }),
].sort();

const hash = createHash("sha256");
hash.update(await readFile(fileURLToPath(import.meta.url)));
for (const path of paths) if (path !== "./") hash.update(await readFile(join(rootDir, path)));
const version = hash.digest("hex").slice(0, 16);
const worker = `// Generated by scripts/build-offline.ts; do not edit manually.
const CACHE = "pg-static-${version}";
const CACHE_PREFIX = "pg-static-";
const ASSETS = ${JSON.stringify(paths, null, 2)};
// Window client IDs change on a full reload. A group shares one copy of its
// retiring version's immutable modules for as long as any member still exists.
const SCOPE = self.registration.scope;
const STATIC_CACHE = CACHE + ":" + SCOPE;
const HELD_PREFIX = "pg-window-chunks:" + SCOPE + ":";
const ACTIVE_MARKER = SCOPE + ".pg-active-cache";
const members = (key) => key.slice(HELD_PREFIX.length).split(",");
const isChunk = (url) => url.startsWith(SCOPE + "assets/") &&
  /[/][^/]+-[A-Za-z0-9_-]{8}[.](js|css)$/.test(new URL(url).pathname);

self.addEventListener("install", (event) => {
  // A still-fresh shell from the previous release can reference chunks that this
  // release no longer ships. Revalidate every stable URL before installing it.
  const requests = ASSETS.map((path) => {
    const url = new URL(path, SCOPE);
    return new Request(url, { cache: isChunk(url.href) ? "default" : "no-cache" });
  });
  event.waitUntil(caches.open(STATIC_CACHE).then((cache) => cache.addAll(requests)));
});

async function windowGroups(keys) {
  const windows = await self.clients.matchAll({ type: "window", includeUncontrolled: true });
  const live = new Set(windows.filter((client) => client.url.startsWith(SCOPE)).map((client) => client.id));
  const unpinned = new Set(live);
  for (const key of keys.filter((key) => key.startsWith(HELD_PREFIX))) {
    const ids = members(key);
    if (ids.some((id) => live.has(id))) {
      for (const id of ids) unpinned.delete(id);
    } else {
      await caches.delete(key);
    }
  }
  return [...unpinned].sort();
}

async function activate() {
  const keys = await caches.keys();
  const unpinned = await windowGroups(keys);
  const retired = [];
  let previous;
  for (const key of keys.filter((key) => key.startsWith(CACHE_PREFIX) && key !== STATIC_CACHE)) {
    const separator = key.indexOf(":");
    if (separator >= 0 && key.slice(separator + 1) !== SCOPE) continue;
    const cache = await caches.open(key);
    if (!(await cache.match(SCOPE))) continue;
    const requests = await cache.keys();
    // A legacy build could share one cache between several registration scopes.
    // Each precache contains its own directory URL as the navigation shell.
    let own = requests;
    if (separator < 0) {
      const nestedScopes = requests.map((request) => request.url).filter((url) =>
        url !== SCOPE && url.startsWith(SCOPE) && url.endsWith("/"));
      own = requests.filter(({ url }) =>
        url.startsWith(SCOPE) && !nestedScopes.some((scope) => url.startsWith(scope)));
    }
    const retiring = { key, cache, own, shared: own.length !== requests.length };
    retired.push(retiring);
    if (await cache.match(ACTIVE_MARKER)) previous = retiring;
  }
  // Older generators lack an activation marker and predate route splitting.
  if (previous && unpinned.length) {
    const chunks = previous.own.filter((request) => isChunk(request.url));
    if (chunks.length) {
      const held = await caches.open(HELD_PREFIX + unpinned.join(","));
      await Promise.all(chunks.map(async (request) => {
        await held.put(request, await previous.cache.match(request));
      }));
    }
  }
  const current = await caches.open(STATIC_CACHE);
  await current.put(ACTIVE_MARKER, new Response(CACHE));
  await Promise.all(retired.map(async ({ key, cache, own, shared }) => {
    if (!shared) return caches.delete(key);
    await Promise.all(own.map((request) => cache.delete(request)));
    if (!(await cache.keys()).length) await caches.delete(key);
  }));
}

async function releaseClosedWindows() {
  const keys = await caches.keys();
  if (keys.some((key) => key.startsWith(HELD_PREFIX))) await windowGroups(keys);
}

self.addEventListener("activate", (event) => event.waitUntil(activate()));
self.addEventListener("message", (event) => {
  const data = event.data || {};
  // Activation is explicit: the page asks after saving its game best-effort.
  // Extend the event lifetime so the worker cannot be terminated while the
  // activation it requested is still pending.
  if (data.type === "SKIP_WAITING") event.waitUntil(self.skipWaiting());
  else if (data.type === "GET_VERSION" && event.ports && event.ports[0]) event.ports[0].postMessage({ version: CACHE });
  // A page served before the fast-update change asks for this preflight before
  // it sends SKIP_WAITING. Answer it so one rollout is enough; delete this
  // branch once no client predates the change.
  else if (data.type === "PREPARE_UPDATE" && event.ports && event.ports[0]) event.ports[0].postMessage({ ok: true, failed: 0, unconfirmed: 0 });
});
self.addEventListener("fetch", (event) => {
  if (event.request.method !== "GET") return;
  const url = new URL(event.request.url);
  if (url.origin !== self.location.origin || !url.href.startsWith(self.registration.scope)) return;
  if (event.request.mode === "navigate" || /[/]assets[/]index-[^/]+[.]js$/.test(url.pathname))
    event.waitUntil(releaseClosedWindows().catch(() => {}));
  event.respondWith((async () => {
    try {
      const cache = await caches.open(STATIC_CACHE);
      const navigation = event.request.mode === "navigate";
      const cached = await cache.match(navigation ? "./" : event.request, { ignoreSearch: true });
      if (cached) return cached;
      if (!navigation && event.clientId && isChunk(event.request.url)) {
        const key = (await caches.keys()).find((key) =>
          key.startsWith(HELD_PREFIX) && members(key).includes(event.clientId));
        if (key) {
          const held = await (await caches.open(key)).match(event.request);
          if (held) return held;
        }
      }
    } catch {
      // An unavailable local cache must not prevent a working network request.
    }
    return fetch(event.request);
  })());
});
`;
await writeFile(outFile, worker);
console.log(
  `Offline cache ${version}: ${paths.length} assets from ${relative(process.cwd(), rootDir) || "."}`,
);
