import { readdir, readFile, writeFile } from "node:fs/promises";
import { createHash } from "node:crypto";

// The root is the only production source. Run whenever application assets change.
const paths = ["./", "index.html", "favicon.svg", "manifest.webmanifest"];
async function collect(folder) {
  for (const entry of await readdir(new URL(`../${folder}/`, import.meta.url), { withFileTypes: true })) {
    if (entry.isDirectory()) await collect(`${folder}/${entry.name}`);
    else if (!/test|\.txt$/.test(entry.name)) paths.push(`${folder}/${entry.name}`);
  }
}
for (const folder of ["js", "css", "assets/fonts/inter", "assets/img/roles"]) await collect(folder);
paths.push(...["ru_RU", "en_GB", "az_AZ"].map((locale) => `assets/data/${locale}.js`));
paths.sort();
const hash = createHash("sha256");
hash.update(await readFile(new URL(import.meta.url)));
for (const path of paths) if (path !== "./") hash.update(await readFile(new URL(`../${path}`, import.meta.url)));
const version = hash.digest("hex").slice(0, 16);
const worker = `// Generated by scripts/build-offline.mjs; do not edit manually.
const CACHE = "pg-static-${version}";
const ASSETS = ${JSON.stringify(paths, null, 2)};
self.addEventListener("install", (event) => {
  event.waitUntil(caches.open(CACHE).then((cache) => cache.addAll(ASSETS)));
});
self.addEventListener("activate", (event) => {
  event.waitUntil(caches.keys().then((keys) => Promise.all(keys.filter((key) => key.startsWith("pg-static-") && key !== CACHE).map((key) => caches.delete(key)))));
});
self.addEventListener("fetch", (event) => {
  if (event.request.method !== "GET") return;
  const url = new URL(event.request.url);
  if (url.origin !== self.location.origin || !url.href.startsWith(self.registration.scope)) return;
  if (event.request.mode === "navigate") {
    event.respondWith(caches.open(CACHE).then(async (cache) => (await cache.match("./", { ignoreSearch: true })) || fetch(event.request)));
    return;
  }
  event.respondWith(caches.open(CACHE).then(async (cache) => {
    const cached = await cache.match(event.request, { ignoreSearch: true });
    if (cached) return cached;
    return fetch(event.request);
  }));
});
`;
await writeFile(new URL("../sw.js", import.meta.url), worker);
console.log(`Offline cache ${version}: ${paths.length} assets`);
